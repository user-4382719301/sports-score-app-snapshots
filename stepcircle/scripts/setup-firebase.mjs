#!/usr/bin/env node
/**
 * Wires the app to your Firebase project in one step.
 *
 * Usage:
 *   node scripts/setup-firebase.mjs
 *   → paste the firebaseConfig object from the Firebase console
 *     (Project settings → Your apps → Web app), press Enter, then Ctrl-D.
 *
 * What it does:
 *   - writes src/config.ts with your values and SOCIAL_BACKEND = 'firebase'
 *   - writes firebase/.firebaserc so `firebase deploy` targets your project
 *   - prints the remaining commands (login, deploy, builds)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const KEYS = ['apiKey', 'authDomain', 'projectId', 'storageBucket', 'messagingSenderId', 'appId'];

console.log('Paste the firebaseConfig object from the Firebase console,');
console.log('then press Enter and Ctrl-D:\n');
const pasted = readFileSync(0, 'utf8');

const config = {};
for (const key of KEYS) {
  const match = pasted.match(new RegExp(`${key}\\s*[:=]\\s*["']([^"']+)["']`));
  config[key] = match ? match[1] : '';
}

const missing = ['apiKey', 'projectId', 'appId'].filter((k) => !config[k]);
if (missing.length) {
  console.error(`\n✗ Could not find ${missing.join(', ')} in what you pasted.`);
  console.error('  Copy the whole firebaseConfig = { ... } block and try again.');
  process.exit(1);
}

const configTs = `/**
 * App configuration.
 *
 * SOCIAL_BACKEND:
 *  - 'demo'     — on-device fake friends/competitions; zero setup, works in Expo Go.
 *  - 'firebase' — real multi-user backend (see docs/BACKEND.md).
 *
 * Generated by scripts/setup-firebase.mjs — rerun it to point at a
 * different Firebase project.
 */
export const SOCIAL_BACKEND: 'demo' | 'firebase' = 'firebase';

export const FIREBASE_CONFIG = {
  apiKey: '${config.apiKey}',
  authDomain: '${config.authDomain}',
  projectId: '${config.projectId}',
  storageBucket: '${config.storageBucket}',
  messagingSenderId: '${config.messagingSenderId}',
  appId: '${config.appId}',
};
`;

writeFileSync(join(root, 'src', 'config.ts'), configTs);
writeFileSync(
  join(root, 'firebase', '.firebaserc'),
  JSON.stringify({ projects: { default: config.projectId } }, null, 2) + '\n'
);

console.log(`\n✓ src/config.ts now points at "${config.projectId}" with the Firebase backend enabled.`);
console.log('✓ firebase/.firebaserc written.\n');
console.log('Remaining steps (from the stepcircle/ directory):\n');
console.log('  npm install -g firebase-tools');
console.log('  firebase login');
console.log('  npm --prefix firebase/functions install');
console.log('  (cd firebase && firebase deploy --only firestore,functions)\n');
console.log('Reminder: enable Anonymous sign-in and create a Firestore database');
console.log('in the console first, and upgrade to the Blaze plan so the');
console.log('functions deploy is allowed. Then rebuild the app on each phone.');
